import Foundation

public enum ResearchMarketRegion: String, CaseIterable, Sendable, Identifiable {
    case worldwide, usa, europe, asia, japan, latam
    public var id: String { rawValue }
}
public struct ResearchMarketOption: Equatable, Sendable, Identifiable {
    public let id: String
    public let labelKey: String
    public init(id: String, labelKey: String) {
        self.id = id
        self.labelKey = labelKey
    }
}
public struct ResearchMarketEntry: Equatable, Sendable, Identifiable {
    public let symbol: String
    public let label: String
    public let region: ResearchMarketRegion?
    public var id: String { symbol }
    public init(symbol: String, label: String, region: ResearchMarketRegion? = nil) {
        self.symbol = symbol
        self.label = label
        self.region = region
    }
}
public struct ResearchMarketGroup: Equatable, Sendable {
    public let titleKey: String?
    public let entries: [ResearchMarketEntry]
    public init(titleKey: String? = nil, entries: [ResearchMarketEntry]) {
        self.titleKey = titleKey
        self.entries = entries
    }
}
