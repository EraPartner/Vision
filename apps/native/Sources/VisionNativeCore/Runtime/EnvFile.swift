import Foundation

/// The runtime id (`normalizeRuntimeId`).
public struct RuntimeNames: Sendable, Equatable {
    public let id: String

    public init(runtimeId: String) throws {  // lint:allow raw-id runtime directory name of the app variant, not an API entity
        id = try RuntimeNames.normalize(runtimeId)
    }

    /// `normalizeRuntimeId`: lowercase, other characters become `_`, then
    /// `^[a-z][a-z0-9_]{0,31}$`.
    public static func normalize(_ value: String) throws -> String {
        let source = value.isEmpty ? "vision" : value
        let allowed = CharacterSet(charactersIn: "abcdefghijklmnopqrstuvwxyz0123456789_")
        let normalized = String(
            source.lowercased().unicodeScalars.map { scalar -> Character in
                allowed.contains(scalar) ? Character(scalar) : "_"
            })
        guard PathUtilities.fullMatch(normalized, "[a-z][a-z0-9_]{0,31}") else {
            throw NativeRuntimeError("INVALID_RUNTIME_ID", "Invalid native runtime id: \(value)")
        }
        return normalized
    }
}

/// `runtime.env`: the market-data keys and explicit overrides the backend reads through
/// `VISION_NATIVE_ENV_FILE`. Since ADR-263 it holds no database settings: the backend opens
/// `VISION_DATABASE_PATH`, which the runtime passes itself.
public enum RuntimeEnvFile {
    /// `NATIVE_ENV_HEADER`: the whole content of a new file.
    public static let header = "# Auto-generated by Vision native runtime. Do not commit or share this file.\n"

    /// `parseEnvFile`: `KEY=value` lines; blank lines, comments and invalid keys are
    /// skipped and the value is everything after the first `=`.
    public static func parse(_ contents: String) -> [String: String] {
        var result: [String: String] = [:]
        for line in contents.split(separator: "\n", omittingEmptySubsequences: false) {
            let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
            if trimmed.isEmpty || trimmed.hasPrefix("#") { continue }
            guard let equals = trimmed.firstIndex(of: "="), equals > trimmed.startIndex else { continue }
            let key = trimmed[..<equals].trimmingCharacters(in: .whitespacesAndNewlines)
            guard PathUtilities.fullMatch(key, "[A-Z_][A-Z0-9_]*") else { continue }
            result[key] = String(trimmed[trimmed.index(after: equals)...])
        }
        return result
    }

    /// `stripRetiredNativeEnv`: removes every line that assigns a retired key; other lines
    /// stay byte-identical, and the text is returned unchanged when nothing was removed.
    public static func stripRetired(_ contents: String) -> String {
        let lines = contents.split(separator: "\n", omittingEmptySubsequences: false).map(String.init)
        let kept = lines.filter { line in
            guard let key = PathUtilities.firstMatchGroups(line, #"^\s*([A-Z_][A-Z0-9_]*)\s*="#)?[1] else {
                return true
            }
            return !RuntimeConstants.retiredEnvironmentKeys.contains(key)
        }
        return kept.count == lines.count ? contents : kept.joined(separator: "\n")
    }

    /// `validateApplicationEnv`: the non-empty market-data keys of `values`, in key order;
    /// a value with a line break or NUL throws.
    public static func validateApplicationEnvironment(_ values: [String: String]) throws -> [(String, String)] {
        var filtered: [(String, String)] = []
        for key in RuntimeConstants.applicationEnvironmentKeys {
            guard let value = values[key], !value.isEmpty else { continue }
            guard !value.contains(where: { $0 == "\r" || $0 == "\n" || $0 == "\0" }) else {
                throw NativeRuntimeError("INVALID_RUNTIME_ENV", "Invalid value for native environment key \(key)")
            }
            filtered.append((key, value))
        }
        return filtered
    }

    /// `importApplicationEnv`: replaces each imported key's line in place, appends new
    /// keys, and ends the file with one newline.
    public static func importing(_ additions: [(String, String)], into contents: String) -> String {
        var body = contents
        if body.hasSuffix("\n") { body.removeLast() }
        var lines = body.split(separator: "\n", omittingEmptySubsequences: false).map(String.init)
        var byKey: [String: Int] = [:]
        for (index, line) in lines.enumerated() {
            if let key = PathUtilities.firstMatchGroups(line, #"^([A-Z_][A-Z0-9_]*)="#)?[1] {
                byKey[key] = index
            }
        }
        for (key, value) in additions {
            let line = "\(key)=\(value)"
            if let index = byKey[key] {
                lines[index] = line
            } else {
                lines.append(line)
            }
        }
        return lines.joined(separator: "\n") + "\n"
    }
}
