import Foundation

/// Database and role names derived from the runtime id (`runtimeNames`).
public struct RuntimeNames: Sendable, Equatable {
    public let id: String
    public let database: String
    public let adminRole: String
    public let ownerRole: String
    public let appRole: String

    public init(runtimeId: String) throws {
        let id = try RuntimeNames.normalize(runtimeId)
        self.id = id
        database = id
        adminRole = "\(id)_admin"
        ownerRole = "\(id)_owner"
        appRole = "\(id)_app"
    }

    /// `normalizeRuntimeId`: lowercase, other characters become `_`, then
    /// `^[a-z][a-z0-9_]{0,31}$`.
    public static func normalize(_ value: String) throws -> String {
        let source = value.isEmpty ? "vision" : value
        let allowed = CharacterSet(charactersIn: "abcdefghijklmnopqrstuvwxyz0123456789_")
        let normalized = String(
            source.lowercased().unicodeScalars.map { scalar -> Character in
                allowed.contains(scalar) ? Character(scalar) : "_"
            })
        guard PathUtilities.fullMatch(normalized, "[a-z][a-z0-9_]{0,31}") else {
            throw NativeRuntimeError("INVALID_RUNTIME_ID", "Invalid native runtime id: \(value)")
        }
        return normalized
    }
}

/// `validateIdentifier`: a lowercase PostgreSQL identifier of at most 63 characters.
public func validateIdentifier(_ value: String?, _ label: String) throws -> String {
    let identifier = value ?? ""
    guard PathUtilities.fullMatch(identifier, "[a-z][a-z0-9_]{0,62}") else {
        throw NativeRuntimeError("INVALID_IDENTIFIER", "Invalid \(label)")
    }
    return identifier
}

/// `requireHexSecret`: generated credentials are 64 lowercase hexadecimal characters.
public func requireHexSecret(_ value: String?) throws -> String {
    let secret = value ?? ""
    guard PathUtilities.isSHA256(secret) else {
        throw NativeRuntimeError(
            "INVALID_SECRET", "Native database credentials must be 64 lowercase hexadecimal characters")
    }
    return secret
}

/// The parsed `runtime.env` (`NativeDatabaseConfig`). It holds secrets, so it is not
/// `CustomStringConvertible` and must never be logged.
public struct DatabaseConfig: Sendable, Equatable {
    public let database: String
    public let adminRole: String
    public let adminPassword: String
    public let appRole: String
    public let appPassword: String
    public let ownerRole: String
    public let ownerPassword: String
    public let host: String
    public let port: Int
    public let environment: [String: String]
    public let analysisPassword: String
}

/// `runtime.env`: the generated database configuration the backend reads through
/// `VISION_NATIVE_ENV_FILE`.
public enum RuntimeEnvFile {
    /// `parseEnvFile`: `KEY=value` lines; blank lines, comments and invalid keys are
    /// skipped and the value is everything after the first `=`.
    public static func parse(_ contents: String) -> [String: String] {
        var result: [String: String] = [:]
        for line in contents.split(separator: "\n", omittingEmptySubsequences: false) {
            let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
            if trimmed.isEmpty || trimmed.hasPrefix("#") { continue }
            guard let equals = trimmed.firstIndex(of: "="), equals > trimmed.startIndex else { continue }
            let key = trimmed[..<equals].trimmingCharacters(in: .whitespacesAndNewlines)
            guard PathUtilities.fullMatch(key, "[A-Z_][A-Z0-9_]*") else { continue }
            result[key] = String(trimmed[trimmed.index(after: equals)...])
        }
        return result
    }

    /// `nativeEnvContents`: fresh random credentials for the three generated roles.
    public static func render(names: RuntimeNames, postgresPort: Int, random: any RandomSource) -> String {
        let appPassword = random.hex(byteCount: 32)
        let ownerPassword = random.hex(byteCount: 32)
        let adminPassword = random.hex(byteCount: 32)
        let host = RuntimeConstants.loopbackHost
        return [
            "# Auto-generated by Vision native runtime. Do not commit or share this file.",
            "VISION_POSTGRES_ADMIN_ROLE=\(names.adminRole)",
            "VISION_POSTGRES_ADMIN_PASSWORD=\(adminPassword)",
            "DATABASE_URL=postgresql://\(names.appRole):\(appPassword)@\(host):\(postgresPort)/\(names.database)",
            "DATABASE_URL_MIGRATIONS=postgresql://\(names.ownerRole):\(ownerPassword)@\(host):\(postgresPort)/\(names.database)",
            "",
        ].joined(separator: "\n")
    }

    /// `ensureNativeAdminEnv`: adds a cluster administrator to an older file.
    public static func ensureAdmin(_ contents: String, names: RuntimeNames, random: any RandomSource) -> String {
        let environment = parse(contents)
        if !(environment["VISION_POSTGRES_ADMIN_ROLE"] ?? "").isEmpty,
            !(environment["VISION_POSTGRES_ADMIN_PASSWORD"] ?? "").isEmpty
        {
            return contents
        }
        let base = contents.hasSuffix("\n") ? contents : contents + "\n"
        return "\(base)VISION_POSTGRES_ADMIN_ROLE=\(names.adminRole)\nVISION_POSTGRES_ADMIN_PASSWORD=\(random.hex(byteCount: 32))\n"
    }

    /// `stripRetiredNativeEnv`: removes every line that assigns a retired key; other lines
    /// stay byte-identical, and the text is returned unchanged when nothing was removed.
    public static func stripRetired(_ contents: String) -> String {
        let lines = contents.split(separator: "\n", omittingEmptySubsequences: false).map(String.init)
        let kept = lines.filter { line in
            guard let key = PathUtilities.firstMatchGroups(line, #"^\s*([A-Z_][A-Z0-9_]*)\s*="#)?[1] else {
                return true
            }
            return !RuntimeConstants.retiredEnvironmentKeys.contains(key)
        }
        return kept.count == lines.count ? contents : kept.joined(separator: "\n")
    }

    /// `databaseConfigFromEnv`: validates the generated URLs, roles and secrets.
    public static func databaseConfig(_ contents: String) throws -> DatabaseConfig {
        let environment = parse(contents)
        let appURL = try PostgresURL(environment["DATABASE_URL"])
        let ownerURL = try PostgresURL(environment["DATABASE_URL_MIGRATIONS"])
        let database = try validateIdentifier(appURL.database, "database name")
        let adminRole = try validateIdentifier(
            environment["VISION_POSTGRES_ADMIN_ROLE"], "cluster administrator role")
        let appRole = try validateIdentifier(appURL.user, "application role")
        let ownerRole = try validateIdentifier(ownerURL.user, "owner role")
        let port = try validateNetworkPort(
            appURL.port ?? RuntimeConstants.defaultPostgresPort, "native PostgreSQL port")
        guard ownerURL.database == database else {
            throw NativeRuntimeError("INVALID_RUNTIME_ENV", "Native database URLs target different databases")
        }
        guard appURL.host == RuntimeConstants.loopbackHost, ownerURL.host == RuntimeConstants.loopbackHost else {
            throw NativeRuntimeError("INVALID_RUNTIME_ENV", "Native PostgreSQL URLs must use 127.0.0.1")
        }
        let ownerPort = try validateNetworkPort(
            ownerURL.port ?? RuntimeConstants.defaultPostgresPort, "migration PostgreSQL port")
        guard ownerPort == port else {
            throw NativeRuntimeError("INVALID_RUNTIME_ENV", "Native database URLs target different PostgreSQL ports")
        }
        let explicitAnalysis = environment["DATABASE_URL_ANALYSIS"].flatMap { $0.isEmpty ? nil : $0 }
        var analysisURL = try PostgresURL(explicitAnalysis ?? environment["DATABASE_URL"])
        if explicitAnalysis == nil { analysisURL.user = RuntimeConstants.analysisRole }
        guard analysisURL.user == RuntimeConstants.analysisRole,
            analysisURL.host == appURL.host,
            (analysisURL.port ?? 5432) == port,
            analysisURL.database == database,
            !analysisURL.password.isEmpty
        else {
            throw NativeRuntimeError(
                "INVALID_RUNTIME_ENV", "Native analysis URL must use the fixed executor on the native database")
        }
        _ = try requireHexSecret(appURL.password)
        _ = try requireHexSecret(ownerURL.password)
        let adminPassword = try requireHexSecret(environment["VISION_POSTGRES_ADMIN_PASSWORD"])
        guard Set([adminRole, ownerRole, appRole]).count == 3 else {
            throw NativeRuntimeError("INVALID_RUNTIME_ENV", "Native PostgreSQL roles must be distinct")
        }
        return DatabaseConfig(
            database: database,
            adminRole: adminRole,
            adminPassword: adminPassword,
            appRole: appRole,
            appPassword: appURL.password,
            ownerRole: ownerRole,
            ownerPassword: ownerURL.password,
            host: appURL.host,
            port: port,
            environment: environment,
            analysisPassword: analysisURL.password
        )
    }
}

/// `validateNetworkPort`: an integer from 1 to 65535.
public func validateNetworkPort(_ port: Int, _ label: String) throws -> Int {
    guard (1...65535).contains(port) else {
        throw NativeRuntimeError("INVALID_PORT", "Invalid \(label)")
    }
    return port
}

/// The parts of a `postgresql://user:password@host:port/database` URL the runtime reads,
/// percent-decoded like `decodeURIComponent` on the WHATWG URL fields.
struct PostgresURL {
    var user: String
    var password: String
    var host: String
    var port: Int?
    var database: String

    init(_ raw: String?) throws {
        guard let raw, let components = URLComponents(string: raw), components.scheme != nil,
            let host = components.host
        else {
            throw NativeRuntimeError("INVALID_RUNTIME_ENV", "Invalid URL")
        }
        user = components.user ?? ""
        password = components.password ?? ""
        self.host = host
        port = components.port
        let path = components.path
        database = path.hasPrefix("/") ? String(path.dropFirst()) : path
    }
}
