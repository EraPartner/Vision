// swift-tools-version: 6.0
import PackageDescription

// Vision Native (ADR-204). VisionNativeCore holds the non-UI logic; VisionNativeUI holds the
// SwiftUI screens of phase 2 and the generated String Catalog. The app target in project.yml
// links both; `swift test --package-path apps/native` runs the tests.
let package = Package(
    name: "VisionNativeCore",
    defaultLocalization: "en",
    platforms: [.macOS("26.0")],
    products: [
        .library(name: "VisionNativeCore", targets: ["VisionNativeCore"]),
        .library(name: "VisionNativeUI", targets: ["VisionNativeUI"]),
    ],
    targets: [
        .target(name: "VisionNativeCore"),
        .target(
            name: "VisionNativeUI",
            dependencies: ["VisionNativeCore"],
            // Localizable.xcstrings is generated by scripts/native-strings.ts. Fonts holds the
            // web's latin subsets (@fontsource, OFL-1.1) as TrueType, registered by VisionFonts:
            // Inter 400, 400 italic, 500, 600 and 700, and Fraunces 400, 600 and 700, with the
            // OFL texts (OFL.txt for Fraunces, OFL-Inter.txt for Inter).
            resources: [.copy("Resources/Localizable.xcstrings"), .copy("Resources/Fonts")]
        ),
        .testTarget(
            name: "VisionNativeCoreTests",
            dependencies: ["VisionNativeCore"],
            // The Vision 1.0.2 backup fixture (packaging/electron/backup/fixtures), byte for byte,
            // and the per-schema JSON samples scripts/native-fixtures.ts generates from openapi.yaml.
            resources: [.copy("Fixtures/vision-1.0.2-sanitized.visionbak.enc"), .copy("Fixtures/api")]
        ),
        .testTarget(
            name: "VisionNativeUITests",
            dependencies: ["VisionNativeUI", "VisionNativeCore"]
        ),
    ]
)
