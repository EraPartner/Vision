/**
 * Shared helpers for the Vision Native generators (ADR-204 phase 2): the
 * scripts/native-*.ts files write Swift sources and the String Catalog under
 * apps/native/ from the web app's sources, and CI regenerates them to check
 * that the committed copies have not drifted.
 */

export const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "..",
);

export function repoPath(...parts: string[]): string {
  return path.join(REPO_ROOT, ...parts);
}

/** The header every generated Swift file starts with. */
export function generatedHeader(source: string, command: string): string {
  return [
    `// Generated by ${source}. Do not edit by hand:`,
    `// run \`bun run ${command}\` from the repository root.`,
    "",
  ].join("\n");
}

/**
 * Reads a list file: one entry per line, `#` starts a comment, blank lines are
 * ignored. A repeated entry is an error, so a list cannot silently disagree
 * with itself.
 */
export function parseListFile(text: string, label: string): string[] {
  const entries: string[] = [];
  const seen = new Set<string>();
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, "").trim();
    if (!line) continue;
    if (seen.has(line)) throw new Error(`${label}: "${line}" is listed twice.`);
    seen.add(line);
    entries.push(line);
  }
  return entries;
}

const SWIFT_ESCAPES: Record<string, string> = {
  "\\": "\\\\",
  '"': '\\"',
  "\n": "\\n",
  "\r": "\\r",
  "\t": "\\t",
};

/** A Swift string literal for any text. */
export function swiftString(value: string): string {
  let out = "";
  for (const char of value) {
    const escaped = SWIFT_ESCAPES[char];
    if (escaped !== undefined) {
      out += escaped;
      continue;
    }
    const code = char.codePointAt(0) ?? 0;
    out += code < 0x20 || code === 0x7f ? `\\u{${code.toString(16)}}` : char;
  }
  return `"${out}"`;
}

