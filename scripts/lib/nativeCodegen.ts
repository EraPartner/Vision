function words(name: string): string[] {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
}

/** `rate_to_eur` → `rateToEur`, `card-foreground` → `cardForeground`. */
export function camelCase(name: string): string {
  const parts = words(name);
  if (parts.length === 0) throw new Error(`Cannot name "${name}" in Swift.`);
  const [first = "", ...rest] = parts;
  let result =
    first.charAt(0).toLowerCase() +
    first.slice(1) +
    rest.map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");
  if (/^[0-9]/.test(result)) result = `_${result}`;
  return result;
}

/** `getExchangeRates` → `GetExchangeRates`, `high-contrast` → `HighContrast`. */
export function pascalCase(name: string): string {
  const camel = camelCase(name);
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

/** A Swift identifier, escaped with backticks when it is a keyword. */
export function swiftIdentifier(name: string): string {
  return SWIFT_KEYWORDS.has(name) ? `\`${name}\`` : name;
}

/** Writes a generated file, creating its directory. */
export function writeGenerated(file: string, content: string): void {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, "utf8");
  console.log(`[native] wrote ${path.relative(REPO_ROOT, file)}`);
}

interface YamlParser {
  parseYaml(text: string): unknown;
}

/**
 * Parses YAML with the parser `bun run generate:types` reads openapi.yaml
 * with: openapi-typescript's @redocly/openapi-core, resolved from the declared
 * openapi-typescript devDependency. Bun's built-in YAML parser rejects parts of
 * openapi.yaml, and the repository declares no other YAML package.
 */
export function parseYaml(text: string): unknown {
  const fromRoot = createRequire(repoPath("package.json"));
  const generator = fromRoot.resolve("openapi-typescript");
  const redocly = createRequire(generator)(
    "@redocly/openapi-core",
  ) as YamlParser;
  return redocly.parseYaml(text);
}
